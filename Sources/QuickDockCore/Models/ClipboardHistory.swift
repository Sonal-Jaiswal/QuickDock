import Foundation

/// One remembered clipboard text.
public struct ClipboardEntry: Codable, Identifiable, Equatable, Hashable, Sendable {
    public var id: UUID
    public var text: String
    public var copiedAt: Date
    /// Name of the app that was frontmost when the text was copied (best effort).
    public var sourceApp: String?
    /// Pinned entries are never trimmed and survive "Clear History".
    public var isPinned: Bool

    public init(id: UUID = UUID(), text: String, copiedAt: Date = Date(), sourceApp: String? = nil, isPinned: Bool = false) {
        self.id = id
        self.text = text
        self.copiedAt = copiedAt.wholeSeconds
        self.sourceApp = sourceApp
        self.isPinned = isPinned
    }

    /// A single-line preview for lists.
    public var preview: String {
        let collapsed = text.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }.joined(separator: " ⏎ ")
        return collapsed.count > 300 ? String(collapsed.prefix(300)) + "…" : collapsed
    }
}

/// Clipboard history for text, with privacy rules built in.
///
/// Copies that password managers and other apps mark as concealed, transient or
/// auto-generated (see nspasteboard.org) are never recorded.
public struct ClipboardHistory: Codable, Equatable, Sendable {
    public static let limitRange = 10...200
    public static let defaultLimit = 50
    /// Very large copies (logs, documents) are skipped rather than stored.
    public static let maximumTextLength = 50_000

    public private(set) var entries: [ClipboardEntry]
    public var limit: Int {
        didSet {
            limit = Self.limitRange.clamp(limit)
            trim()
        }
    }

    public init(entries: [ClipboardEntry] = [], limit: Int = ClipboardHistory.defaultLimit) {
        self.entries = entries
        self.limit = Self.limitRange.clamp(limit)
        trim()
    }

    /// Pasteboard types that mean "do not record this copy".
    public static let ignoredPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.agilebits.onepassword7",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    public static func shouldIgnore(pasteboardTypes types: [String]) -> Bool {
        types.contains { ignoredPasteboardTypes.contains($0) }
    }

    /// Records a copy. Returns `true` if the history changed.
    /// Re-copying existing text moves it to the top instead of duplicating it.
    @discardableResult
    public mutating func record(_ text: String, sourceApp: String? = nil, at date: Date = Date()) -> Bool {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maximumTextLength else { return false }
        if let index = entries.firstIndex(where: { $0.text == text }) {
            var existing = entries.remove(at: index)
            existing.copiedAt = date.wholeSeconds
            if let sourceApp { existing.sourceApp = sourceApp }
            entries.insert(existing, at: 0)
            return true
        }
        entries.insert(ClipboardEntry(text: text, copiedAt: date, sourceApp: sourceApp), at: 0)
        trim()
        return true
    }

    public mutating func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
    }

    public mutating func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].isPinned.toggle()
    }

    /// Removes everything except pinned entries.
    public mutating func clearUnpinned() {
        entries.removeAll { !$0.isPinned }
    }

    public mutating func removeAll() {
        entries.removeAll()
    }

    /// Pinned first, then most recent first.
    public var ordered: [ClipboardEntry] {
        entries.filter(\.isPinned) + entries.filter { !$0.isPinned }
    }

    public func search(_ query: String) -> [ClipboardEntry] {
        let normalized = SearchMatcher.normalize(query)
        guard !normalized.isEmpty else { return ordered }
        return ordered.filter { SearchMatcher.normalize($0.text).contains(normalized) }
    }

    private mutating func trim() {
        var unpinnedSeen = 0
        entries = entries.filter { entry in
            if entry.isPinned { return true }
            unpinnedSeen += 1
            return unpinnedSeen <= limit
        }
    }
}

/// Saves clipboard history to `clipboard.json` only when the user enables "Remember after quitting".
public final class ClipboardStore {
    public let fileURL: URL

    public init(directory: URL) {
        fileURL = directory.appendingPathComponent("clipboard.json")
    }

    public func load() -> ClipboardHistory? {
        guard let data = try? Data(contentsOf: fileURL) else { return nil }
        return try? LibraryStore.makeDecoder().decode(ClipboardHistory.self, from: data)
    }

    public func save(_ history: ClipboardHistory) throws {
        try FileManager.default.createDirectory(at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        try LibraryStore.makeEncoder().encode(history).write(to: fileURL, options: [.atomic])
    }

    public func delete() {
        try? FileManager.default.removeItem(at: fileURL)
    }
}
